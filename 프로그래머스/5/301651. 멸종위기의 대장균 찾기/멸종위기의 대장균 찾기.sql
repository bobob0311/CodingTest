WITH RECURSIVE GE AS (
    SELECT 
        1 AS N, 
        ID 
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT
        G.N +1 AS N,
        D.ID
    FROM ECOLI_DATA AS D JOIN GE AS G
        ON G.ID = D.PARENT_ID
)
SELECT COUNT(*) AS COUNT, N AS GENERATION
FROM GE LEFT JOIN ECOLI_DATA AS D ON GE.ID = D.PARENT_ID
WHERE D.ID IS NULL
GROUP BY N
